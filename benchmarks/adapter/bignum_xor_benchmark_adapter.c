/**
 * @file bignum_xor_benchmark_adapter.c
 * @brief bignum_xor domain adapter for benchmark-framework v1.0.0.
 *
 * The official Makefile retains the template filename, but this implementation
 * exposes only bignum_xor semantics: one source operand is initialized by the
 * dataset callback and the operation callback deterministically constructs the
 * second operand before calling bignum_xor(result, a, b). The lifecycle is
 * validate axes, initialize normalized source rows, construct a deterministic
 * operand, invoke the typed operation, and hash every capacity word. Dataset
 * generation is O(B) per row and each operation/checksum is O(B), where B is
 * BIGNUM_CAPACITY; no adapter heap allocation or mutable global state exists.
 * The callback state is caller-owned benchmark-core storage and is never shared
 * between workers.
 */
#include "bignum_xor_benchmark_adapter.h"

#include <stddef.h>
#include <stdint.h>
#include <string.h>

#include <bignum.h>
#include "bignum_xor.h"

/** @brief Initial offset basis for the adapter's 64-bit FNV checksum. */
#define BIGNUM_XOR_BENCHMARK_FNV_OFFSET UINT64_C(1469598103934665603)
/** @brief Prime multiplier for each checksum word and finalization step. */
#define BIGNUM_XOR_BENCHMARK_FNV_PRIME UINT64_C(1099511628211)

/** @brief Input-row classes generated by the adapter; values are internal and immutable. */
typedef enum {
    BIGNUM_XOR_PROFILE_ZERO = 0, /**< Zero source row; len and every word are zero. */
    BIGNUM_XOR_PROFILE_NONZERO = 1, /**< Non-zero normalized source row. */
    BIGNUM_XOR_PROFILE_MIXED = 2 /**< Alternating zero and non-zero source rows. */
} bignum_xor_input_profile_t;

/** @brief Deterministic second-operand patterns used by bignum_xor. */
typedef enum {
    BIGNUM_XOR_OP_ZERO = 0, /**< Every operand word is zero. */
    BIGNUM_XOR_OP_MASK = 1, /**< Every operand word is UINT64_MAX. */
    BIGNUM_XOR_OP_RANDOM = 2, /**< Every operand word is deterministic pseudo-random data. */
    BIGNUM_XOR_OP_MIXED = 3 /**< Alternating mask and deterministic pseudo-random words. */
} bignum_xor_operation_profile_t;

/**
 * @brief Checks whether a borrowed token belongs to a fixed vocabulary.
 * @param[in] value Borrowed NUL-terminated token; NULL is invalid.
 * @param[in] allowed NULL-terminated borrowed vocabulary; NULL is invalid.
 * @param[out] accepted Receives a named boolean and is written only on valid pointers.
 * @return Named adapter status; no allocation or ownership transfer occurs.
 * @details A linear scan is used because each vocabulary is small and immutable.
 * @par Thread safety Safe for concurrent read-only calls.
 * @par Complexity O(V) time and O(1) space, where V is vocabulary length.
 */
static bignum_xor_benchmark_status_t string_allowed(
    const char *value,
    const char *const *allowed,
    benchmark_boolean_t *accepted)
{
    if (value == NULL || allowed == NULL || accepted == NULL) {
        return BIGNUM_XOR_BENCHMARK_STATUS_NULL_ARGUMENT;
    }
    *accepted = BENCHMARK_BOOLEAN_FALSE;
    for (size_t i = 0U; allowed[i] != NULL; ++i) {
        if (strcmp(value, allowed[i]) == 0) {
            *accepted = BENCHMARK_BOOLEAN_TRUE;
            break;
        }
    }
    return BIGNUM_XOR_BENCHMARK_STATUS_SUCCESS;
}

/**
 * @brief Converts token membership into the adapter status model.
 * @param[in] value Borrowed profile token.
 * @param[in] allowed NULL-terminated allowed-token array.
 * @return SUCCESS for a member, INVALID_PROFILE for a non-member, or NULL_ARGUMENT.
 * @details Output state is local; the caller's strings remain unchanged.
 * @par Thread safety Safe for concurrent read-only calls.
 * @par Complexity O(V) time and O(1) space.
 */
static bignum_xor_benchmark_status_t validate_axis(
    const char *value,
    const char *const *allowed)
{
    benchmark_boolean_t accepted;
    bignum_xor_benchmark_status_t status = string_allowed(value, allowed, &accepted);
    if (status != BIGNUM_XOR_BENCHMARK_STATUS_SUCCESS) {
        return status;
    }
    return accepted == BENCHMARK_BOOLEAN_TRUE
        ? BIGNUM_XOR_BENCHMARK_STATUS_SUCCESS
        : BIGNUM_XOR_BENCHMARK_STATUS_INVALID_PROFILE;
}

/**
 * @brief Maps input_kind text to its internal profile enum.
 * @param[in] value Borrowed workload token.
 * @param[out] profile Receives the enum only when value/profile are non-NULL and valid.
 * @return SUCCESS, NULL_ARGUMENT, xor INVALID_PROFILE; output is unchanged on failure.
 * @par Thread safety Safe for independent calls.
 * @par Complexity O(1) for the fixed three-token vocabulary.
 */
static bignum_xor_benchmark_status_t parse_input_profile(
    const char *value,
    bignum_xor_input_profile_t *profile)
{
    if (value == NULL || profile == NULL) {
        return BIGNUM_XOR_BENCHMARK_STATUS_NULL_ARGUMENT;
    }
    if (strcmp(value, "zero") == 0) *profile = BIGNUM_XOR_PROFILE_ZERO;
    else if (strcmp(value, "nonzero") == 0) *profile = BIGNUM_XOR_PROFILE_NONZERO;
    else if (strcmp(value, "mixed") == 0) *profile = BIGNUM_XOR_PROFILE_MIXED;
    else return BIGNUM_XOR_BENCHMARK_STATUS_INVALID_PROFILE;
    return BIGNUM_XOR_BENCHMARK_STATUS_SUCCESS;
}

/**
 * @brief Maps operation_kind text to an internal AND operand pattern.
 * @param[in] value Borrowed workload token.
 * @param[out] profile Receives the pattern on success and is unchanged on failure.
 * @return SUCCESS, NULL_ARGUMENT, xor INVALID_PROFILE.
 * @par Thread safety Safe for independent calls.
 * @par Complexity O(1) for the fixed four-token vocabulary.
 */
static bignum_xor_benchmark_status_t parse_operation_profile(
    const char *value,
    bignum_xor_operation_profile_t *profile)
{
    if (value == NULL || profile == NULL) {
        return BIGNUM_XOR_BENCHMARK_STATUS_NULL_ARGUMENT;
    }
    if (strcmp(value, "xor-zero") == 0) *profile = BIGNUM_XOR_OP_ZERO;
    else if (strcmp(value, "xor-mask") == 0) *profile = BIGNUM_XOR_OP_MASK;
    else if (strcmp(value, "xor-random") == 0) *profile = BIGNUM_XOR_OP_RANDOM;
    else if (strcmp(value, "xor-mixed") == 0) *profile = BIGNUM_XOR_OP_MIXED;
    else return BIGNUM_XOR_BENCHMARK_STATUS_INVALID_PROFILE;
    return BIGNUM_XOR_BENCHMARK_STATUS_SUCCESS;
}

/**
 * @brief Advances the deterministic adapter pseudo-random generator.
 * @param[in,out] state Caller-owned non-NULL state; zero is replaced by a fixed non-zero seed.
 * @return Next deterministic 64-bit value; state ownership remains with the caller.
 * @details The xorshift sequence is used only for reproducible workload generation,
 * not for security. It has O(1) time and O(1) space.
 * @par Thread safety Safe when each invocation has an independent state pointer.
 */
static uint64_t next_value(uint64_t *state)
{
    if (*state == 0U) *state = UINT64_C(0x9E3779B97F4A7C15);
    *state ^= *state << 7U;
    *state ^= *state >> 9U;
    *state ^= *state << 8U;
    return *state;
}

/**
 * @brief Selects a valid logical operand length from workload profiles.
 * @param[in] workload Borrowed validated workload descriptor.
 * @param[in,out] state Deterministic generator state used only for variable length.
 * @param[out] length Receives a value in 1..BIGNUM_CAPACITY on success.
 * @return SUCCESS, NULL_ARGUMENT, xor INVALID_PROFILE; length is not published on failure.
 * @details Near-capacity selects the largest valid storage length and never times an overflow path.
 * @par Thread safety Safe for independent state/workload pairs.
 * @par Complexity O(1) time and O(1) space.
 */
static bignum_xor_benchmark_status_t choose_length(
    const benchmark_workload_t *workload,
    uint64_t *state,
    size_t *length)
{
    if (workload == NULL || state == NULL || length == NULL) {
        return BIGNUM_XOR_BENCHMARK_STATUS_NULL_ARGUMENT;
    }
    if (strcmp(workload->size_profile, "one") == 0) *length = 1U;
    else if (strcmp(workload->size_profile, "quarter") == 0) {
        *length = BIGNUM_CAPACITY / 4U == 0U ? 1U : BIGNUM_CAPACITY / 4U;
    } else if (strcmp(workload->size_profile, "half") == 0) {
        *length = BIGNUM_CAPACITY / 2U == 0U ? 1U : BIGNUM_CAPACITY / 2U;
    } else if (strcmp(workload->size_profile, "near-capacity") == 0 ||
               strcmp(workload->capacity_profile, "near-capacity") == 0) {
        *length = BIGNUM_CAPACITY;
    } else {
        *length = 1U + (size_t)(next_value(state) % BIGNUM_CAPACITY);
    }
    return *length <= BIGNUM_CAPACITY
        ? BIGNUM_XOR_BENCHMARK_STATUS_SUCCESS
        : BIGNUM_XOR_BENCHMARK_STATUS_INVALID_PROFILE;
}

/**
 * @brief Initializes one benchmark-core source row as a normalized bignum_t.
 * @param[out] state Caller-allocated benchmark-core state storage; non-NULL and writable.
 * @param[in] sequence_index Stable dataset row index.
 * @param[in] workload Immutable borrowed workload descriptor.
 * @param[in] adapter_context Unused project context; must be NULL for this binding.
 * @return BENCHMARK_ADAPTER_STATUS_SUCCESS xor INPUT_ERROR; state is fully cleared
 * before any successful return and no partial row is accepted.
 * @details The callback selects zero/nonzero/mixed input, chooses a logical length,
 * fills words from the fixed seed, and preserves normalized bignum representation.
 * @par Thread safety Safe for independent state rows and workers.
 * @par Complexity O(B) time in the nonzero path and O(B) zeroing time.
 */
static benchmark_adapter_status_t bignum_xor_initialize(
    void *state,
    uint64_t sequence_index,
    const benchmark_workload_t *workload,
    void *adapter_context)
{
    bignum_t *number = state;
    bignum_xor_input_profile_t input_profile;
    uint64_t random_state;
    size_t length;
    bignum_xor_benchmark_status_t status;

    (void)adapter_context;
    if (number == NULL || workload == NULL) return BENCHMARK_ADAPTER_STATUS_INPUT_ERROR;
    status = bignum_xor_benchmark_validate_workload(workload);
    if (status != BIGNUM_XOR_BENCHMARK_STATUS_SUCCESS ||
        parse_input_profile(workload->input_kind, &input_profile) !=
            BIGNUM_XOR_BENCHMARK_STATUS_SUCCESS) {
        return BENCHMARK_ADAPTER_STATUS_INPUT_ERROR;
    }
    memset(number, 0, sizeof(*number));
    if (input_profile == BIGNUM_XOR_PROFILE_ZERO ||
        (input_profile == BIGNUM_XOR_PROFILE_MIXED && (sequence_index & 1U) == 0U)) {
        return BENCHMARK_ADAPTER_STATUS_SUCCESS;
    }
    random_state = workload->seed ^ (sequence_index + UINT64_C(0x9E3779B97F4A7C15));
    status = choose_length(workload, &random_state, &length);
    if (status != BIGNUM_XOR_BENCHMARK_STATUS_SUCCESS) return BENCHMARK_ADAPTER_STATUS_INPUT_ERROR;
    number->len = length;
    for (size_t i = 0U; i < length; ++i) number->words[i] = next_value(&random_state);
    if (number->words[length - 1U] == 0U) number->words[length - 1U] = UINT64_C(1);
    return BENCHMARK_ADAPTER_STATUS_SUCCESS;
}

/**
 * @brief Executes one in-place bignum_xor operation on a mutable state copy.
 * @param[in,out] state Independent caller-owned bignum_t copy supplied by core.
 * @param[in] iteration Stable logical iteration used for deterministic operand data.
 * @param[in] workload Immutable borrowed profile descriptor.
 * @param[in] adapter_context Unused project context; must be NULL.
 * @return BENCHMARK_ADAPTER_STATUS_SUCCESS only when bignum_xor returns success;
 * INPUT_ERROR for invalid callback inputs/profile and OPERATION_ERROR otherwise.
 * @details The second operand is stack-owned for this callback, has the same
 * normalized length, and is discarded after the typed operation returns.
 * @warning The state must not be concurrently accessed by another worker.
 * @par Thread safety Safe when each worker receives an independent state copy.
 * @par Complexity O(B) time and O(B) stack space for the second operand.
 */
static benchmark_adapter_status_t bignum_xor_operation(
    void *state,
    uint64_t iteration,
    const benchmark_workload_t *workload,
    void *adapter_context)
{
    bignum_t *number = state;
    bignum_t operand;
    bignum_xor_operation_profile_t operation_profile;
    bignum_xor_status_t operation_status;
    uint64_t random_state;

    (void)adapter_context;
    if (number == NULL || workload == NULL || number->len > BIGNUM_CAPACITY ||
        parse_operation_profile(workload->operation_kind, &operation_profile) !=
            BIGNUM_XOR_BENCHMARK_STATUS_SUCCESS) {
        return number != NULL && number->len > BIGNUM_CAPACITY
            ? BENCHMARK_ADAPTER_STATUS_OPERATION_ERROR
            : BENCHMARK_ADAPTER_STATUS_INPUT_ERROR;
    }
    memset(&operand, 0, sizeof(operand));
    operand.len = number->len;
    random_state = workload->seed ^ (iteration + UINT64_C(0xD1B54A32D192ED03));
    for (size_t i = 0U; i < operand.len; ++i) {
        uint64_t random_value = next_value(&random_state);
        if (operation_profile == BIGNUM_XOR_OP_ZERO) operand.words[i] = 0U;
        else if (operation_profile == BIGNUM_XOR_OP_MASK) operand.words[i] = UINT64_MAX;
        else if (operation_profile == BIGNUM_XOR_OP_MIXED) {
            operand.words[i] = (i & 1U) == 0U ? UINT64_MAX : random_value;
        } else operand.words[i] = random_value;
    }
    operation_status = bignum_xor(number, number, &operand);
    return operation_status == BIGNUM_XOR_SUCCESS
        ? BENCHMARK_ADAPTER_STATUS_SUCCESS
        : BENCHMARK_ADAPTER_STATUS_OPERATION_ERROR;
}

/**
 * @brief Produces an observable checksum of a post-operation bignum_t.
 * @param[in] state Read-only caller-owned state; NULL produces checksum zero.
 * @param[in] iteration Stable iteration mixed into the result.
 * @param[in] adapter_context Unused project context.
 * @return FNV-style 64-bit checksum consumed by benchmark-core; no ownership changes.
 * @details Every capacity word, logical length, and iteration participates so the
 * compiler cannot remove the measured operation as unobservable.
 * @par Thread safety Safe for concurrent reads of independent xor immutable states.
 * @par Complexity O(B) time and O(1) space.
 */
static uint64_t bignum_xor_checksum(
    const void *state,
    uint64_t iteration,
    void *adapter_context)
{
    const bignum_t *number = state;
    uint64_t checksum = BIGNUM_XOR_BENCHMARK_FNV_OFFSET;
    (void)adapter_context;
    if (number == NULL) return 0U;
    for (size_t i = 0U; i < BIGNUM_CAPACITY; ++i) {
        checksum ^= number->words[i];
        checksum *= BIGNUM_XOR_BENCHMARK_FNV_PRIME;
    }
    checksum ^= (uint64_t)number->len ^ iteration;
    return checksum * BIGNUM_XOR_BENCHMARK_FNV_PRIME;
}

/* The public contract is canonical in the header; this implementation validates
 * every workload axis before dataset allocation and returns atomically. */
bignum_xor_benchmark_status_t bignum_xor_benchmark_validate_workload(
    const benchmark_workload_t *workload)
{
    static const char *const input_values[] = { "zero", "nonzero", "mixed", NULL };
    static const char *const operation_values[] = {
        "xor-zero", "xor-mask", "xor-random", "xor-mixed", NULL
    };
    static const char *const measure_values[] = { "end-to-end", "kernel-only", NULL };
    static const char *const size_values[] = {
        "one", "quarter", "half", "variable", "near-capacity", NULL
    };
    static const char *const capacity_values[] = { "normal", "near-capacity", NULL };

    if (workload == NULL) return BIGNUM_XOR_BENCHMARK_STATUS_NULL_ARGUMENT;
    if (validate_axis(workload->input_kind, input_values) != BIGNUM_XOR_BENCHMARK_STATUS_SUCCESS ||
        validate_axis(workload->operation_kind, operation_values) != BIGNUM_XOR_BENCHMARK_STATUS_SUCCESS ||
        validate_axis(workload->measure_mode, measure_values) != BIGNUM_XOR_BENCHMARK_STATUS_SUCCESS ||
        validate_axis(workload->size_profile, size_values) != BIGNUM_XOR_BENCHMARK_STATUS_SUCCESS ||
        validate_axis(workload->capacity_profile, capacity_values) != BIGNUM_XOR_BENCHMARK_STATUS_SUCCESS) {
        return BIGNUM_XOR_BENCHMARK_STATUS_INVALID_PROFILE;
    }
    return BIGNUM_XOR_BENCHMARK_STATUS_SUCCESS;
}

/* The public contract is canonical in the header; this implementation installs
 * all callbacks in one aggregate assignment and publishes no partial binding. */
bignum_xor_benchmark_status_t bignum_xor_benchmark_adapter_init(
    benchmark_adapter_t *adapter)
{
    if (adapter == NULL) return BIGNUM_XOR_BENCHMARK_STATUS_NULL_ARGUMENT;
    *adapter = (benchmark_adapter_t){
        .benchmark_name = "bignum_xor",
        .state_size = sizeof(bignum_t),
        .success_code = BENCHMARK_ADAPTER_STATUS_SUCCESS,
        .adapter_context = NULL,
        .initialize = bignum_xor_initialize,
        .operation = bignum_xor_operation,
        .checksum = bignum_xor_checksum
    };
    return BIGNUM_XOR_BENCHMARK_STATUS_SUCCESS;
}
